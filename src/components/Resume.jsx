import React from 'react';

const Resume = React.forwardRef(({ job, applicant }, ref) => {
  const displayName = applicant.name || 'Applicant Name';
  const displayEmail = applicant.email || 'name@example.com';
  const displayPhone = applicant.phone || '+91 98765 43210';
  const displayLocation = applicant.location || job.location;
  const displayObjective = applicant.objective || `Apply for the ${job.title} role with a strong background in relevant technologies.`;
  const displaySkills = Array.isArray(applicant.skills)
    ? applicant.skills
    : applicant.skills
    ? applicant.skills.split(',').map((skill) => skill.trim())
    : ['AWS', 'Kubernetes', 'Terraform'];
  const displayEducation = applicant.education || 'Bachelor of Technology in Computer Science';
  const displayCertifications = Array.isArray(applicant.certifications)
    ? applicant.certifications
    : applicant.certifications
    ? applicant.certifications.split(',').map((cert) => cert.trim())
    : [];
  const displayExperience = applicant.experience || 'Built scalable cloud infrastructure, CI/CD automation, and operational tooling for modern IT teams.';
  const displayRequirements = Array.isArray(applicant.requirements) ? applicant.requirements : [];

  return (
    <article ref={ref} className="resume-card p-4 rounded shadow-sm">
      <div className="d-flex flex-column flex-md-row justify-content-between align-items-start mb-4">
        <div>
          <h2 className="mb-1">{displayName}</h2>
          <p className="text-primary mb-2">{job.title} Candidate</p>
        </div>
        <div className="text-md-end mt-3 mt-md-0">
          <p className="mb-1"><strong>Email:</strong> {displayEmail}</p>
          <p className="mb-1"><strong>Phone:</strong> {displayPhone}</p>
          <p className="mb-0"><strong>Location:</strong> {displayLocation}</p>
        </div>
      </div>

      <section className="mb-4">
        <h5 className="mb-2">Professional Summary</h5>
        <p className="text-muted mb-0">{displayObjective}</p>
      </section>

      <section className="row mb-4 gap-3">
        <div className="col-md-6">
          <h6 className="mb-2">Role</h6>
          <p className="mb-1"><strong>Position:</strong> {job.title}</p>
          <p className="mb-0"><strong>Company:</strong> {job.company}</p>
        </div>
        <div className="col-md-6">
          <h6 className="mb-2">Employment</h6>
          <p className="mb-1"><strong>Type:</strong> {job.type}</p>
          <p className="mb-0"><strong>Location:</strong> {job.location}</p>
        </div>
      </section>

      <section className="mb-4">
        <h6 className="mb-2">Experience Summary</h6>
        <p className="text-muted">{displayExperience}</p>
      </section>

      <section className="row mb-4">
        <div className="col-md-6 mb-3 mb-md-0">
          <h6 className="mb-2">Education</h6>
          <p className="mb-0 text-muted">{displayEducation}</p>
        </div>
        <div className="col-md-6">
          <h6 className="mb-2">Certifications</h6>
          {displayCertifications.length > 0 ? (
            <ul className="list-unstyled mb-0 text-muted">
              {displayCertifications.map((cert) => (
                <li key={cert}>• {cert}</li>
              ))}
            </ul>
          ) : (
            <p className="mb-0 text-muted">No certifications added yet.</p>
          )}
        </div>
      </section>

      <section className="mb-4">
        <h6 className="mb-2">Core Skills</h6>
        <div className="d-flex flex-wrap gap-2">
          {displaySkills.map((skill) => (
            <span key={skill} className="badge bg-secondary text-white">
              {skill}
            </span>
          ))}
        </div>
      </section>

      {displayRequirements.length > 0 && (
        <section className="mb-4">
          <h6 className="mb-2">Job Alignment</h6>
          <ul className="list-unstyled mb-0 text-muted">
            {displayRequirements.map((requirement) => (
              <li key={requirement}>• {requirement}</li>
            ))}
          </ul>
        </section>
      )}

      <footer className="text-end text-muted small mt-4">
        Generated by the Job Portal Dashboard AI resume assistant.
      </footer>
    </article>
  );
});

export default Resume;
